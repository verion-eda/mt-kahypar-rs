/// A **partitioning context** bundles *all* algorithmic parameters.
pub struct Context {
    raw: NonNull<sys::mt_kahypar_context_t>,
}
// SAFETY: Mt-KaHyPar's C API is designed for multi-threaded use via TBB.
// The opaque context handle may be sent across threads; all C-level
// synchronisation is handled internally by the library.
unsafe impl Send for Context {}
// SAFETY: same as Send - the library handles internal synchronisation.
unsafe impl Sync for Context {}

impl Drop for Context {
    fn drop(&mut self) {
        // SAFETY: Drop runs at most once.
        unsafe { sys::mt_kahypar_free_context(self.raw.as_ptr()) };
    }
}

impl Context {
    /// Start building a [`Context`].
    ///
    /// Requires an [`Init`] token to prove the thread pool has been
    /// initialized.
    pub fn builder(_init: &Init) -> ContextBuilder {
        ContextBuilder::default()
    }
}

pub struct PartitioningParams {
    /// The number of partitions.
    pub k: i32,
    /// The epsilon value (1+epsilon imbalance).
    pub epsilon: f64,
    /// The objective function used.
    pub objective: Objective,
}

/// Fluent builder for [`Context`].  Construct via [`Context::builder`].
#[derive(Default)]
pub struct ContextBuilder {
    preset: Preset,
    params: Option<PartitioningParams>,
    seed: Option<usize>,
    verbose: bool,
}

impl ContextBuilder {
    /// Apply a preset in the beginning.
    pub fn preset(mut self, p: Preset) -> Self {
        self.preset = p;
        self
    }

    /// The partitioner params.
    pub fn params(mut self, params: PartitioningParams) -> Self {
        self.params = Some(params);
        self
    }

    /// Random seed (for deterministic partitioning algorithms).
    pub fn seed(mut self, seed: usize) -> Self {
        self.seed = Some(seed);
        self
    }

    /// Whether to print verbose partitioning logs to stderr.
    pub fn verbose(mut self, v: bool) -> Self {
        self.verbose = v;
        self
    }

    /// Build the context.
    pub fn build(self) -> Result<Context> {
        let raw_ctx = {
            // SAFETY: the preset enum value is always valid; the function
            // returns null only on internal allocation failure,
            // checked immediately below.
            let raw_ctx = NonNull::new(unsafe {
                sys::mt_kahypar_context_from_preset(self.preset.into())
            })
            .ok_or_else(|| Error {
                status: Status::SystemError,
                message: "mt_kahypar_context_from_preset returned NULL".into(),
            })?;
            raw_ctx
        };

        if let Some(seed) = self.seed {
            // SAFETY: mt_kahypar_set_seed takes a plain usize; no
            // preconditions.
            unsafe { sys::mt_kahypar_set_seed(seed) };
        }
        if self.verbose {
            let s = CString::new("1").unwrap();
            let mut err = sys::mt_kahypar_error_t {
                msg: ptr::null(),
                msg_len: 0,
                status: sys::mt_kahypar_status_t::SUCCESS,
            };
            // SAFETY: raw_ctx is non-null (by construction) and s is a valid
            // null-terminated string that outlives this call.
            let st = unsafe {
                sys::mt_kahypar_set_context_parameter(
                    raw_ctx.as_ptr(),
                    sys::mt_kahypar_context_parameter_type_t::VERBOSE,
                    s.as_ptr(),
                    &mut err,
                )
            };
            check_status(st, &mut err)?;
        }
        if let Some(params) = self.params {
            // SAFETY: raw_ctx is non-null (by construction) and `params` are
            // plain values with no pointer aliasing concerns.
            unsafe {
                sys::mt_kahypar_set_partitioning_parameters(
                    raw_ctx.as_ptr(),
                    params.k,
                    params.epsilon,
                    params.objective.into(),
                )
            };
        }

        Ok(Context { raw: raw_ctx })
    }
}

