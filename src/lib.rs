/// A (Hyper)graph to be partitioned.
pub struct Hypergraph<'ctx> {
    raw: sys::mt_kahypar_hypergraph_t,
    ctx: &'ctx Context,
    num_vertices: usize,
}
// SAFETY: Mt-KaHyPar's hypergraph handles are internally thread-safe.
unsafe impl<'ctx> Send for Hypergraph<'ctx> {}
// SAFETY: same as Send - the library handles internal synchronisation.
unsafe impl<'ctx> Sync for Hypergraph<'ctx> {}

impl<'ctx> Drop for Hypergraph<'ctx> {
    fn drop(&mut self) {
        // SAFETY: raw is non-null (guaranteed by construction) and Drop runs
        // at most once.
        unsafe { sys::mt_kahypar_free_hypergraph(self.raw) };
    }
}

impl<'ctx> Hypergraph<'ctx> {
    /// Load from file (Metis / hMetis).
    ///
    /// Note that we use different (hyper)graph data structures for different
    /// configurations. Make sure that you partition the hypergraph with the
    /// same configuration as it is loaded.
    pub fn from_file(
        path: &str,
        ctx: &'ctx Context,
        format: FileFormat,
    ) -> Result<Self> {
        let c_path = CString::new(path).unwrap();
        let mut err = sys::mt_kahypar_error_t {
            msg: ptr::null(),
            msg_len: 0,
            status: sys::mt_kahypar_status_t::SUCCESS,
        };
        // SAFETY: c_path is a valid null-terminated string that outlives this
        // call; ctx.raw is non-null (guaranteed by Context construction).
        let hg = unsafe {
            sys::mt_kahypar_read_hypergraph_from_file(
                c_path.as_ptr(),
                ctx.raw.as_ptr(),
                format.into(),
                &mut err,
            )
        };
        if hg.hypergraph.is_null() {
            return Err(Error {
                status: Status::InvalidInput,
                message: unsafe {
                    // SAFETY: the C library always sets err.msg on failure.
                    let m =
                        CStr::from_ptr(err.msg).to_string_lossy().into_owned();
                    sys::mt_kahypar_free_error_content(&mut err);
                    m
                },
            });
        }
        // SAFETY: hg is non-null (checked above).
        let n = unsafe { sys::mt_kahypar_num_hypernodes(hg) as usize };
        Ok(Hypergraph {
            raw: hg,
            ctx,
            num_vertices: n,
        })
    }

    /// Constructs a hypergraph from a given adjacency array that specifies the
    /// hyperedges.
    ///
    /// For example:
    /// ``` text
    /// hyperedge_indices: | 0   | 2       | 6     | 9     | 12
    /// hyperedges:        | 0 2 | 0 1 3 4 | 3 4 6 | 2 5 6 |
    /// ```
    /// Defines a hypergraph with four hyperedges, e.g., `e_0 = {0,2}, e_1 =
    /// {0,1,3,4}, ...` `hyperedge_indices` **must** end with
    /// `hyperedges.len()`. note: For unweighted hypergraphs, you can pass
    /// None to either hyperedge_weights or vertex_weights.
    pub fn from_adjacency(
        ctx: &'ctx Context,
        num_vertices: usize,
        hyperedge_indices: &[usize],
        hyperedges: &[usize],
        hyperedge_weights: Option<&[i32]>,
        vertex_weights: Option<&[i32]>,
    ) -> Result<Self> {
        assert_eq!(
            hyperedge_indices.last().copied().unwrap_or(0),
            hyperedges.len(),
            "indices array must terminate with |E|",
        );

        let mut err = sys::mt_kahypar_error_t {
            msg: ptr::null(),
            msg_len: 0,
            status: sys::mt_kahypar_status_t::SUCCESS,
        };
        // SAFETY: ctx.raw is non-null (guaranteed by construction). All slice
        // pointers are valid for their respective lengths. Null is passed for
        // absent optional weight arrays, which the C API accepts.
        let hg = unsafe {
            sys::mt_kahypar_create_hypergraph(
                ctx.raw.as_ptr(),
                num_vertices as _,
                (hyperedge_indices.len() - 1) as _,
                hyperedge_indices.as_ptr(),
                hyperedges.as_ptr() as _,
                hyperedge_weights.map_or(ptr::null(), |w| w.as_ptr())
                    as *const sys::mt_kahypar_hyperedge_weight_t,
                vertex_weights.map_or(ptr::null(), |w| w.as_ptr())
                    as *const sys::mt_kahypar_hypernode_weight_t,
                &mut err,
            )
        };
        if hg.hypergraph.is_null() {
            return Err(Error {
                status: Status::InvalidInput,
                message: unsafe {
                    // SAFETY: the C library always sets err.msg on failure.
                    let m =
                        CStr::from_ptr(err.msg).to_string_lossy().into_owned();
                    sys::mt_kahypar_free_error_content(&mut err);
                    m
                },
            });
        }
        Ok(Hypergraph {
            raw: hg,
            ctx,
            num_vertices,
        })
    }

    /* ------------ Partitioning & Mapping ---------------- */

    /// Partitions a (hyper)graph with the configuration specified in the
    /// partitioning context.
    ///
    /// Before partitioning, the number of blocks, imbalance parameter and
    /// objective function must be set in the partitioning context.
    pub fn partition(&self) -> Result<PartitionedHypergraph<'ctx>> {
        let mut err = sys::mt_kahypar_error_t {
            msg: ptr::null(),
            msg_len: 0,
            status: sys::mt_kahypar_status_t::SUCCESS,
        };
        let ctx = self.ctx;
        let num_v = self.num_vertices;
        // SAFETY: self.raw and ctx.raw are non-null (guaranteed by
        // construction).
        let phg = unsafe {
            sys::mt_kahypar_partition(self.raw, ctx.raw.as_ptr(), &mut err)
        };
        if phg.partitioned_hg.is_null() {
            return Err(Error {
                status: Status::OtherError,
                message: unsafe {
                    // SAFETY: the C library always sets err.msg on failure.
                    let m =
                        CStr::from_ptr(err.msg).to_string_lossy().into_owned();
                    sys::mt_kahypar_free_error_content(&mut err);
                    m
                },
            });
        }
        Ok(PartitionedHypergraph {
            raw: phg,
            ctx,
            num_vertices: num_v,
        })
    }

    /// Map onto a target graph (Steiner-tree objective).
    pub fn map(
        &self,
        target: &mut TargetGraph<'ctx>,
    ) -> Result<PartitionedHypergraph<'ctx>> {
        assert_eq!(self.ctx.raw, target.ctx.raw, "context mismatch");
        let mut err = sys::mt_kahypar_error_t {
            msg: ptr::null(),
            msg_len: 0,
            status: sys::mt_kahypar_status_t::SUCCESS,
        };
        let ctx = self.ctx;
        let num_v = self.num_vertices;
        // SAFETY: self.raw, target.raw, and ctx.raw are all non-null
        // (guaranteed by construction). Context identity is asserted above.
        let phg = unsafe {
            sys::mt_kahypar_map(
                self.raw,
                target.raw.as_ptr(),
                ctx.raw.as_ptr(),
                &mut err,
            )
        };
        if phg.partitioned_hg.is_null() {
            return Err(Error {
                status: Status::OtherError,
                message: unsafe {
                    // SAFETY: the C library always sets err.msg on failure.
                    let m =
                        CStr::from_ptr(err.msg).to_string_lossy().into_owned();
                    sys::mt_kahypar_free_error_content(&mut err);
                    m
                },
            });
        }
        Ok(PartitionedHypergraph {
            raw: phg,
            ctx,
            num_vertices: num_v,
        })
    }

    /* ------------ Introspection ---------------- */

    #[inline]
    pub fn num_nodes(&self) -> usize {
        self.num_vertices
    }
    #[inline]
    pub fn num_edges(&self) -> usize {
        // SAFETY: self.raw is non-null (guaranteed by construction).
        unsafe { sys::mt_kahypar_num_hyperedges(self.raw) as usize }
    }
}

