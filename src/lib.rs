//! # mt-kahypar-rs: non-official Rust bindings for Mt‑KaHyPar
//!
//! **mt-kahypar-rs** provides an idiomatic, ownership‑aware interface to the
//! high‑performance C++ *Mt‑KaHyPar* (multi‑level hypergraph partitioner)
//! library. The bindings compile and link *Mt-KaHyPar* with the TBB dependency.
//! Currently `hwloc` is a dynamic dependency (deviating from the static-only
//! binidings approach followed before) to make use of `hwloc` thread placement.
//!
//! For more details check the docs or the C++ [Mt‑KaHyPar](https://github.com/kahypar/mt-kahypar)
//! repository.
//!
//! ### Example
//!
//! ```no_run
//! use mt_kahypar::*;
//!
//! let init = Init::with_default_threads();
//! let ctx = Context::builder(&init)
//!     .preset(Preset::Deterministic)
//!     .k(4) // number of blocks
//!     .epsilon(0.03) // 3 % imbalance
//!     .objective(Objective::Km1)
//!     .seed(42)
//!     .verbose(false) // change to true to print detailed logs
//!     .build()?;
//!
//! let hg = Hypergraph::from_file("netlist.hgr", &ctx, FileFormat::HMetis)?;
//! let part = hg.partition()?;
//!
//! println!(
//!     "cut = {} | imbalance = {}%",
//!     part.cut(),
//!     part.imbalance() * 100.0
//! );
//! # Ok::<(), mt_kahypar::Error>(())
//! ```
//!
//! ### Notes and safety
//!
//! - [`Init`] is a proof token that the Mt-KaHyPar thread pool has been
//!   initialized. [`Context::builder`] requires one, so the compiler enforces
//!   initialization order. Duplicate [`Init::new`] calls are safe and ignored.
//! - All FFI handles (`Context`, `Hypergraph`, ...) own their native resources
//!   and free them via `Drop`.
//! - Each handle stores an immutable reference to the `Context` it was created
//!   with.  Mixing objects built from *different* contexts triggers an
//!   assertion at the point of use.

/// The raw C bindings for Mt-KaHyPar.
///
/// Generated by the following command.
/// ``` sh
/// bindgen mt-kahypar-upstream/include/mtkahypar.h --default-enum-style rust_non_exhaustive --rust-edition 2024 --rust-target 1.95.0 > src/sys.rs
/// ```
#[allow(non_camel_case_types, non_upper_case_globals)]
pub mod sys;

use std::{
    ffi::{CStr, CString},
    ptr::{self, NonNull},
    sync::Once,
};

static INIT: Once = Once::new();

/// Proof that Mt-KaHyPar's thread pool has been initialized.
///
/// Construct with [`Init::new`] or [`Init::with_default_threads`] before
/// creating any [`Context`]. Duplicate calls are safe and no-ops after the
/// first.
#[derive(Clone)]
pub struct Init(());

impl Init {
    /// Initialize the Mt-KaHyPar thread pool.
    ///
    /// * `num_threads` - maximum number of worker threads to spawn.
    /// * `interleaved` - whether NUMA interleaved allocation should be enabled.
    pub fn new(num_threads: usize, interleaved: bool) -> Self {
        // SAFETY: `Once` guarantees this runs exactly once. The C function has
        // no preconditions beyond being called before other API functions which
        // the Init proof enforces.
        INIT.call_once(|| unsafe {
            sys::mt_kahypar_initialize(num_threads, interleaved);
        });
        Init(())
    }

    /// Initialize with as many threads as logical CPUs.
    pub fn with_default_threads() -> Self {
        let num_threads = std::thread::available_parallelism()
            .map(|n| n.get())
            .unwrap_or(1);
        Self::new(num_threads, true)
    }
}

/// Library‑level error wrapper returned by most fallible API calls.
#[derive(Debug)]
pub struct Error {
    pub status: Status,
    pub message: String,
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{:?}: {}", self.status, self.message)
    }
}
impl std::error::Error for Error {}

pub type Result<T, E = Error> = std::result::Result<T, E>;

/// Mirror of `mt_kahypar_status_t`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Status {
    Success,
    InvalidInput,
    InvalidParameter,
    UnsupportedOperation,
    SystemError,
    OtherError,
}
impl From<sys::mt_kahypar_status_t> for Status {
    fn from(s: sys::mt_kahypar_status_t) -> Self {
        use sys::mt_kahypar_status_t::*;
        match s {
            SUCCESS => Status::Success,
            INVALID_INPUT => Status::InvalidInput,
            INVALID_PARAMETER => Status::InvalidParameter,
            UNSUPPORTED_OPERATION => Status::UnsupportedOperation,
            SYSTEM_ERROR => Status::SystemError,
            // non_exhaustive has no effect in this own crate.
            OTHER_ERROR => Status::OtherError,
        }
    }
}

/// Objective functions.
///
/// See [upstream docs](https://github.com/gzz2000/mt-kahypar-sc/tree/master?tab=readme-ov-file#supported-objective-functions) for their descriptions.
#[derive(Clone, Copy)]
pub enum Objective {
    /// Cut-Net Metric
    Cut,
    /// Connectivity Metric
    Km1,
    /// Sum-of-external-Degrees Metric
    Soed,
}
impl From<Objective> for sys::mt_kahypar_objective_t {
    fn from(o: Objective) -> Self {
        match o {
            Objective::Cut => sys::mt_kahypar_objective_t::CUT,
            Objective::Km1 => sys::mt_kahypar_objective_t::KM1,
            Objective::Soed => sys::mt_kahypar_objective_t::SOED,
        }
    }
}

/// High‑level preset *recipes* shipped with Mt‑KaHyPar.
///
/// The default is now `Deterministic` rather than legacy `Default`.
#[derive(Clone, Copy, Default)]
pub enum Preset {
    /// Deterministic & repeatable runs.
    #[default]
    Deterministic,
    /// Deterministic with higher quality (slower than `Deterministic`).
    DeterministicQuality,
    /// Tweaked for large‑`k` (many blocks) instances.
    LargeK,
    /// Legacy default of the C API.
    Default,
    /// Better quality at higher runtime.
    Quality,
    /// Highest available quality settings.
    HighestQuality,
}
impl From<Preset> for sys::mt_kahypar_preset_type_t {
    fn from(p: Preset) -> Self {
        use sys::mt_kahypar_preset_type_t::*;
        match p {
            Preset::Deterministic => DETERMINISTIC,
            Preset::DeterministicQuality => DETERMINISTIC_QUALITY,
            Preset::LargeK => LARGE_K,
            Preset::Default => DEFAULT,
            Preset::Quality => QUALITY,
            Preset::HighestQuality => HIGHEST_QUALITY,
        }
    }
}

